import { launch, admin, B, shot, check } from "./lib.mjs";
import { execSync } from "node:child_process";
const b = await launch();
const W = Number(process.env.W || 1280), tag = W < 600 ? "390" : "1280";
const { ctx, page, errors } = await admin(b, { width: W, height: W < 600 ? 844 : 900 });
const go = async (p = "/admin/appearance") => page.goto(B + p, { waitUntil: "networkidle", timeout: 180000 });
let clicks = 0; const click = async (loc) => { clicks++; await loc.click(); };
await go();
check(await page.locator("h1").innerText() === "Apparence", "titre Apparence");
// 1. catalogue : installer et utiliser en 1 clic
clicks = 0;
await click(page.locator('[data-catalogue-skin="e2e-duo"] button:has-text("Installer et utiliser")'));
await page.waitForSelector('[data-skin-card="e2e-duo"][aria-current="true"]', { timeout: 120000 });
console.log("CLICS catalogue -> activé :", clicks);
check(await page.locator('[data-testid="undo-banner"]').isVisible(), "bandeau Annuler visible");
await shot(page, `10-active-${tag}`);
// 2. aperçu de basic avant de l'utiliser
await click(page.locator('[data-skin-card="basic"] button:has-text("Aperçu")'));
await page.waitForSelector('[data-testid="preview-frame"]', { timeout: 60000 });
const fr = page.frameLocator('[data-testid="preview-frame"]');
await fr.locator("body").waitFor();
await page.waitForTimeout(1500);
check(await page.locator("dialog[open]").count() === 1, "fenêtre d'aperçu ouverte");
const skinInFrame = await page.frames().find((f) => f.url().includes("curiosa_skin_preview"))?.evaluate(() => document.documentElement.dataset.skin);
check(skinInFrame === "basic", "aperçu de basic dans la fenêtre", String(skinInFrame));
await shot(page, `11-preview-basic-${tag}`, false);
await page.keyboard.press("Escape");
check(await page.locator("dialog[open]").count() === 0, "Échap ferme l'aperçu");
// 3. retouches des deux modes
await click(page.locator('input[name="palette"][value="both"]').locator("xpath=ancestor::label"));
await page.locator('[data-testid="color-tab-dark"]').click();
await page.locator('[data-testid="color-panel-dark"] button[data-testid="theme-custom"]').click();
await page.locator('input[name="dark_background"]').fill("#101018").catch(() => {});
await page.evaluate(() => { const el = document.querySelector('input[name="dark_background"]'); const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set; set.call(el, "#101018"); el.dispatchEvent(new Event("input", { bubbles: true })); });
await page.waitForTimeout(300);
await page.locator('[data-testid="color-panel-dark"] button:has-text("Aucun")').count();
// texte pâle sur fond sombre : champ texte (mode avancé requis) -> on passe par l'accent proche du fond
await page.evaluate(() => { const el = document.querySelector('input[name="dark_accent"]'); const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set; set.call(el, "#15151f"); el.dispatchEvent(new Event("input", { bubbles: true })); });
await page.waitForTimeout(400);
const warn = await page.locator('[data-testid="warn-accent"], [data-testid="theme-contrast-warning"]').first().innerText().catch(() => "");
check(/mode sombre/.test(warn), "avertissement de contraste sous le champ (mode sombre)", warn.slice(0, 120));
await shot(page, `12-both-warning-${tag}`);
// clavier : onglets
await page.locator('[data-testid="color-tab-dark"]').focus();
await page.keyboard.press("ArrowRight");
check(await page.locator('[data-testid="color-tab-light"]').getAttribute("aria-selected") === "true", "flèche : onglet Clair");
// enregistrer
await page.evaluate(() => { const el = document.querySelector('input[name="dark_accent"]'); const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set; set.call(el, "#ffb36b"); el.dispatchEvent(new Event("input", { bubbles: true })); });
await page.locator('[data-testid="floating-bar"] button:has-text("Enregistrer")').click();
await page.waitForSelector('text=Enregistré', { timeout: 60000 }).catch(() => {});
await page.waitForTimeout(1500);
await go();
check(await page.locator('input[name="palette"][value="both"]').isChecked(), "« clair et sombre » gardé après rechargement");
// 4. revenir au skin + annuler
await page.locator('[data-testid="reset-card"] button:has-text("Revenir au skin")').scrollIntoViewIfNeeded();
await click(page.locator('[data-testid="reset-card"] button:has-text("Revenir au skin")'));
await page.locator("[role=alertdialog] button:has-text(\"Continuer\")").click();
await page.waitForTimeout(2500);
await go();
const pal = await page.locator('input[name="palette"][value="single"]').isChecked();
check(pal, "après « Revenir au skin » : un seul mode (valeurs du skin)");
await click(page.locator('[data-testid="undo-banner"] button:has-text("Annuler")'));
await page.waitForTimeout(2500);
await go();
check(await page.locator('input[name="palette"][value="both"]').isChecked(), "Annuler : retouches revenues");
await shot(page, `13-after-undo-${tag}`);
// 5. site public avec le skin, clair/sombre
const pub = await ctx.newPage();
await pub.goto(B + "/", { waitUntil: "networkidle", timeout: 120000 });
check(await pub.evaluate(() => document.documentElement.dataset.skin) === "e2e-duo", "site public : skin actif");
check(await pub.locator('[data-skin-part="mode-switch"]').isVisible(), "bouton Clair/Sombre visible");
await shot(pub, `14-public-${tag}`, false);
await pub.close();
// 6. adresse personnelle : illisible refusé, lisible avec confirmation
await go();
await page.locator('[data-testid="personal-repo"] summary').click();
const url = "https://github.com/e2e/curiosa-skins";
await page.locator("#repoUrl").fill(url + "#gris-pale-v1.0.0:skins/gris-pale");
await page.locator('[data-testid="personal-repo"] button:has-text("Vérifier")').click();
await page.waitForSelector('[data-testid="inspect-panel"]', { timeout: 120000 });
check(/pas assez lisible/.test(await page.locator('[data-testid="inspect-panel"]').innerText()), "skin pâle : « pas assez lisible » dit avant d'installer");
check(await page.locator('[data-testid="personal-repo"] button:has-text("Ajouter ce skin")').count() === 0, "pas de bouton d'ajout pour un skin illisible");
await page.locator("#repoUrl").fill(url + "#calme-clair-v1.0.0:skins/calme-clair");
await page.locator('[data-testid="personal-repo"] button:has-text("Vérifier")').click();
await page.waitForSelector('[data-testid="personal-repo"] button:has-text("Ajouter ce skin")', { timeout: 120000 });
await shot(page, `15-personal-${tag}`);
await page.locator('[data-testid="personal-repo"] button:has-text("Ajouter ce skin")').click();
await page.waitForSelector('[data-testid="personal-repo"] :text("Cochez")', { timeout: 30000 });
check(true, "sans la case : message sous le champ");
await page.locator('[data-testid="personal-repo"] input[name="understood"]').check();
await page.locator('[data-testid="personal-repo"] button:has-text("Ajouter ce skin")').click();
await page.waitForSelector('[data-skin-card="calme-clair"]', { timeout: 120000 });
check(true, "skin personnel ajouté");
// 7. mise à jour puis retour arrière puis retrait
execSync("cd /dev/shm/s7-e2e/skins-repo && cp catalogue/index-1.1.0.json catalogue/index.json && git -c user.email=t@t -c user.name=t add -A && git -c user.email=t@t -c user.name=t commit -q -m idx11 || true"); execSync("rm -f /dev/shm/s7-e2e/site/data/cache/skins-index.json");
await go();
await page.locator('[data-manage="e2e-duo"] summary').click();
await page.locator('[data-manage="e2e-duo"] button:has-text("Chercher une mise à jour")').click();
await page.waitForSelector('[data-testid="update-result"]', { timeout: 120000 });
console.log("MAJ:", (await page.locator('[data-testid="update-result"]').innerText()).replace(/\n/g, " | "));
await shot(page, `16-update-${tag}`);
await page.locator('[data-manage="e2e-duo"] button:has-text("Mettre à jour")').click();
await page.waitForSelector('[data-testid=flash]', { timeout: 120000 });
check(true, "mise à jour faite");
await go();
await page.locator('[data-manage="e2e-duo"] summary').click();
await page.locator('[data-manage="e2e-duo"] button:has-text("Revenir à la version d")').click();
await page.waitForSelector('[data-testid=flash]', { timeout: 120000 });
check(true, "retour arrière fait");
await go();
await page.locator('[data-manage="calme-clair"] summary').click();
await page.locator('[data-manage="calme-clair"] button:has-text("Retirer ce skin")').click();
await page.locator("[role=alertdialog] button:has-text(\"Continuer\")").click();
await page.waitForSelector('[data-testid=flash]', { timeout: 120000 });
check(true, "retrait fait : votre contenu n'a pas changé");
await shot(page, `17-removed-${tag}`);
await ctx.close(); await b.close();
console.log("erreurs console:", errors.length, errors.slice(0, 3));
process.exit(0);
