import { launch, admin, B, shot, check } from "./lib.mjs";
import { DatabaseSync } from "node:sqlite";
const db = new DatabaseSync(process.env.DATA_DIR + "/curiosa.db");
const e = db.prepare("select id, instanceId from Entry limit 1").get();
const inst = db.prepare("select key from ModuleInstance where id=?").get(e.instanceId);
const b = await launch();
const { page, errors } = await admin(b, { width: 390, height: 844 });
await page.goto(`${B}/admin/entries/${e.id}?c=${inst.key}`, { waitUntil: "networkidle", timeout: 180000 });
const d = page.locator('[data-testid="entry-preview"]');
check(await d.count() === 1, "aperçu présent dans l'éditeur d'entrée");
await d.locator("summary").click();
await page.locator('textarea[name="body"]').fill("## Bonjour\n\nUn **texte** pour voir le skin.");
await page.locator('input[name="title"]').fill("Mon titre d'essai");
await page.waitForTimeout(400);
const box = page.locator('[data-testid="entry-preview-box"]');
check((await box.innerText()).includes("Mon titre d'essai") && (await box.innerText()).includes("Bonjour"), "aperçu mis à jour en écrivant");
const bg = await box.evaluate((el) => getComputedStyle(el).backgroundColor);
const adminBg = await page.evaluate(() => getComputedStyle(document.body).backgroundColor);
check(bg !== adminBg, "l'aperçu porte les couleurs du skin, pas celles de l'administration", `${bg} vs ${adminBg}`);
check(await page.evaluate(() => !document.documentElement.dataset.skin), "l'administration n'a pas data-skin");
await box.scrollIntoViewIfNeeded(); await shot(page, "21-entry-preview-390", false);
console.log(errors.slice(0, 2));
await b.close();
