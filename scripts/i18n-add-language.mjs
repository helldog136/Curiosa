#!/usr/bin/env node
// Adds a language to Curiosa with FILES ONLY (no code to write). See docs/TRANSLATING.md.
//
//   node scripts/i18n-add-language.mjs <code>                       skeleton for the core (src/locales/<code>.json) and registration of the language
//   node scripts/i18n-add-language.mjs <code> --modules <repo>      also a skeleton in every module of the modules repository (modules/<id>/locales/<code>.json)
//   node scripts/i18n-add-language.mjs <code> --modules <repo> --no-core --module blog     only one module
//   node scripts/i18n-add-language.mjs <code> --only setup.,login.  only the keys that start with these prefixes (translate the setup wizard first)
//   node scripts/i18n-add-language.mjs --sync                       rebuild src/locales/index.ts from the files of src/locales/ (run after adding or removing a file by hand)
//
// Options: --name "Nederlands" (the name of the language in itself; by default the system knows it), --rtl (right-to-left), --dry-run (write nothing).
//
// A skeleton lists EVERY key with an empty text: an empty text is "not translated yet" and falls back (requested language -> site main language -> English).
// Existing translations are never overwritten: running the script again only adds the keys that are new in English.
// Module skeletons also hold the manifest texts (name, description, setting labels...) under `manifest.<path>` keys; the core merges them at load time.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LANG_CODE_RE, manifestSkeleton, REQUIRED_LANGUAGES } from "../src/core/i18n/audit.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const option = (name) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : undefined; };
const dry = flag("dry-run");
const log = (line) => console.log(line);
const fail = (message) => { console.error(`Error: ${message}`); process.exit(1); };

const localesDir = path.join(root, "src/locales");
const readJson = (file, fallback) => { try { return JSON.parse(fs.readFileSync(file, "utf8")); } catch { return fallback; } };
const writeJson = (file, value) => {
  if (dry) return log(`  (dry run) would write ${path.relative(process.cwd(), file)}`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
  log(`  wrote ${path.relative(process.cwd(), file)}`);
};

/** src/locales/index.ts: one import per language file. */
export function renderIndex(codes) {
  const sorted = [...codes].sort((a, b) => (a === "en" ? -1 : b === "en" ? 1 : a === "fr" ? -1 : b === "fr" ? 1 : a.localeCompare(b)));
  return [
    "// GENERATED by `node scripts/i18n-add-language.mjs --sync` : one line per file `src/locales/<code>.json`. Do not edit by hand.",
    ...sorted.map((c) => `import ${c} from "./${c}.json";`),
    "",
    `export const DICTIONARIES: Record<string, Record<string, string>> = { ${sorted.join(", ")} };`,
    "",
  ].join("\n");
}

function sync() {
  const codes = fs.readdirSync(localesDir).filter((f) => /^[a-z]{2}\.json$/.test(f)).map((f) => f.slice(0, -5));
  for (const required of REQUIRED_LANGUAGES) if (!codes.includes(required)) fail(`src/locales/${required}.json is missing: English and French are always required.`);
  const file = path.join(localesDir, "index.ts");
  const next = renderIndex(codes);
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === next) return log("src/locales/index.ts is up to date.");
  if (dry) return log("(dry run) src/locales/index.ts would change.");
  fs.writeFileSync(file, next);
  log(`Updated src/locales/index.ts (${codes.length} languages: ${codes.join(", ")}).`);
}

function register(code) {
  const file = path.join(localesDir, "languages.json");
  const languages = readJson(file, {});
  if (languages[code]) return log(`  ${code} is already registered in src/locales/languages.json (${languages[code].name}).`);
  let name = option("name");
  if (!name) { try { const n = new Intl.DisplayNames([code], { type: "language" }).of(code); if (n && n !== code) name = n.charAt(0).toLocaleUpperCase(code) + n.slice(1); } catch { /* unknown to this system */ } }
  if (!name) fail(`this system does not know the name of "${code}": add --name "<the name of the language, in that language>".`);
  languages[code] = { name, status: "community", ...(flag("rtl") || ["ar", "he", "fa", "ur"].includes(code) ? { rtl: true } : {}) };
  writeJson(file, languages);
}

/** Existing translations are kept; new keys are added empty; keys that no longer exist in English stay (a human removes them). */
function mergeSkeleton(file, keys) {
  const existing = readJson(file, {});
  const out = { ...existing };
  let added = 0;
  for (const k of keys) if (!(k in out)) { out[k] = ""; added++; }
  // Order: the order of the keys of English, then the keys that are only here.
  const ordered = {};
  for (const k of keys) ordered[k] = out[k];
  for (const k of Object.keys(out)) if (!(k in ordered)) ordered[k] = out[k];
  const done = Object.values(ordered).filter((v) => typeof v === "string" && v.trim()).length;
  writeJson(file, ordered);
  return { added, total: keys.length, done };
}

const only = (option("only") ?? "").split(",").map((s) => s.trim()).filter(Boolean);
const wanted = (k) => !only.length || only.some((p) => k.startsWith(p));

function core(code) {
  const en = readJson(path.join(localesDir, "en.json"), null);
  if (!en) fail("run this command from the Curiosa repository (src/locales/en.json not found), or use --no-core.");
  log(`Core: src/locales/${code}.json`);
  const keys = Object.keys(en).filter(wanted);
  const r = mergeSkeleton(path.join(localesDir, `${code}.json`), keys);
  log(`  ${r.total} keys to translate (${r.added} new, ${r.done} already translated).`);
  register(code);
  sync();
}

function modules(code, repo) {
  const found = [];
  for (const group of ["modules", "examples"]) {
    const dir = path.join(repo, group);
    if (fs.existsSync(dir)) for (const id of fs.readdirSync(dir).sort()) if (fs.existsSync(path.join(dir, id, "module.json"))) found.push({ id, dir: path.join(dir, id) });
  }
  if (!found.length) fail(`no module found in ${repo} (expected modules/<id>/module.json).`);
  const one = option("module");
  const list = one ? found.filter((m) => m.id === one) : found;
  if (!list.length) fail(`module "${one}" not found in ${repo}.`);
  log(`Modules: ${list.length} module(s)`);
  let total = 0;
  for (const m of list) {
    const manifest = readJson(path.join(m.dir, "module.json"), {});
    const runtime = readJson(path.join(m.dir, "locales/en.json"), {});
    const keys = [...manifestSkeleton(manifest).map((x) => x.key), ...Object.keys(runtime)].filter(wanted);
    if (!keys.length) continue;
    const r = mergeSkeleton(path.join(m.dir, "locales", `${code}.json`), keys);
    total += r.total;
    log(`  ${m.id}: ${r.total} keys (${r.added} new, ${r.done} translated)`);
  }
  log(`  ${total} keys to translate in total.`);
}

if (flag("sync")) { sync(); process.exit(0); }
const valueOptions = new Set(["--name", "--modules", "--module", "--only"]);
const code = args.filter((a, i) => !a.startsWith("--") && !valueOptions.has(args[i - 1]))[0];
if (!code || code.startsWith("--")) fail("usage: node scripts/i18n-add-language.mjs <code> [--modules <repo>] [--only prefixes] [--name \"...\"]   |   --sync");
if (!/^[a-z]{2}$/.test(code) || !LANG_CODE_RE.test(code)) fail(`"${code}" is not a two-letter language code (for example nl, de, es, pt).`);
if (REQUIRED_LANGUAGES.includes(code)) fail(`${code} is an official language: it is always complete and kept by the maintainers.`);
const repo = option("modules");
if (!flag("no-core")) core(code);
if (repo) modules(code, path.resolve(repo));
log("");
log("Next: translate the texts (empty = not translated yet, English is shown), then run the tests. See docs/TRANSLATING.md.");
